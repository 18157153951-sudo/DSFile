//
//  DSJailbreakEnv.m — 「越狱模式」实现：jbroot 解析 + entitlements 诊断 + 如实探针
//
//  本文件**不执行任何漏洞、不碰内核**，只做三件事：
//    1) 按 roothide / rootless 的实际做法解析 jbroot（逐条尝试、每条记结果）；
//    2) 打印本 App 自己的 entitlements（判断「权限没给」还是「沙盒在拦」）；
//    3) 用逐路径 + 真实 errno 的探针如实给出结论（EPERM=沙盒拒绝 / EACCES=权限不足 /
//       ENOENT=不存在 / EROFS=只读），绝不假装成功。
//
//  只用公开 POSIX 接口与签名确定的 Security 接口；不猜任何私有函数签名。
//

